-- Solicitudes de recuperación de contraseña simulada. Se numera V5 porque V4 ya está reservada por la
-- migración de auditoría de la feature de publicaciones.
-- El token nunca se guarda en claro: solo su hash SHA-256 en hexadecimal (64 caracteres).
CREATE TABLE solicitud_recuperacion (
    id_solicitud     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario       BIGINT      NOT NULL,
    token_hash       VARCHAR(64) NOT NULL,
    fecha_solicitud  TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_expiracion TIMESTAMPTZ NOT NULL,
    -- Nula mientras la solicitud está vigente; se llena al usarla o al reemplazarla por una nueva.
    fecha_uso        TIMESTAMPTZ,
    CONSTRAINT pk_solicitud_recuperacion PRIMARY KEY (id_solicitud),
    CONSTRAINT fk_solicitud_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT uq_solicitud_token UNIQUE (token_hash),
    CONSTRAINT ck_solicitud_fechas CHECK (fecha_expiracion > fecha_solicitud)
);

CREATE INDEX ix_solicitud_usuario ON solicitud_recuperacion (id_usuario);

COMMENT ON TABLE solicitud_recuperacion IS 'Solicitudes de recuperación de contraseña simulada (sin envío real de correo)';
COMMENT ON COLUMN solicitud_recuperacion.token_hash IS 'SHA-256 en hexadecimal del token entregado al usuario';
