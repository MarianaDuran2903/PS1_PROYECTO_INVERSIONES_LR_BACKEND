-- ============================================================================
-- 7. Triggers de validación (reglas que el MER no puede expresar)
-- ============================================================================

-- Valida que el usuario referenciado tenga el rol esperado.
-- Argumentos del trigger: 0 = rol esperado, 1 = nombre de la columna con el id del usuario.
CREATE OR REPLACE FUNCTION fn_validar_rol_usuario()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    vnIdUsuario BIGINT;
    vvRol       VARCHAR(15);
BEGIN
    vnIdUsuario := (to_jsonb(NEW) ->> TG_ARGV[1])::BIGINT;

    SELECT rol INTO vvRol FROM usuario WHERE id_usuario = vnIdUsuario;

    IF vvRol IS DISTINCT FROM TG_ARGV[0] THEN
        RAISE EXCEPTION 'El usuario % debe tener el rol % (rol actual: %)',
            vnIdUsuario, TG_ARGV[0], COALESCE(vvRol, 'inexistente')
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

-- Solo un ANFITRION crea publicaciones.
CREATE TRIGGER trg_publicacion_rol_anfitrion
    BEFORE INSERT OR UPDATE OF id_anfitrion ON publicacion
    FOR EACH ROW EXECUTE FUNCTION fn_validar_rol_usuario('ANFITRION', 'id_anfitrion');

-- Solo un HUESPED reserva (y, al ser roles disjuntos, nunca su propia publicación).
CREATE TRIGGER trg_reserva_rol_huesped
    BEFORE INSERT OR UPDATE OF id_huesped ON reserva
    FOR EACH ROW EXECUTE FUNCTION fn_validar_rol_usuario('HUESPED', 'id_huesped');

-- Solo las publicaciones ACTIVAS reciben reservas nuevas.
CREATE OR REPLACE FUNCTION fn_validar_reserva_publicacion_activa()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    vvEstadoPublicacion VARCHAR(20);
BEGIN
    SELECT estado INTO vvEstadoPublicacion FROM publicacion WHERE id_publicacion = NEW.id_publicacion;

    IF vvEstadoPublicacion IS DISTINCT FROM 'ACTIVA' THEN
        RAISE EXCEPTION 'La publicacion % no esta ACTIVA (estado actual: %)',
            NEW.id_publicacion, COALESCE(vvEstadoPublicacion, 'inexistente')
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reserva_publicacion_activa
    BEFORE INSERT ON reserva
    FOR EACH ROW EXECUTE FUNCTION fn_validar_reserva_publicacion_activa();

-- Solo se califica una reserva completada: CONFIRMADA y con la fecha de salida ya cumplida.
CREATE OR REPLACE FUNCTION fn_validar_calificacion_reserva_completada()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    vvEstadoReserva VARCHAR(20);
    vdFechaSalida   DATE;
BEGIN
    SELECT estado, fecha_salida INTO vvEstadoReserva, vdFechaSalida
      FROM reserva WHERE id_reserva = NEW.id_reserva;

    IF vvEstadoReserva IS DISTINCT FROM 'CONFIRMADA' OR vdFechaSalida > CURRENT_DATE THEN
        RAISE EXCEPTION 'La reserva % no esta completada (solo se califica una reserva CONFIRMADA cuya fecha de salida ya paso)',
            NEW.id_reserva
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_calificacion_reserva_completada
    BEFORE INSERT ON calificacion
    FOR EACH ROW EXECUTE FUNCTION fn_validar_calificacion_reserva_completada();

