-- ============================================================================
-- 0. Extensiones
-- ============================================================================
-- Necesaria para las restricciones de exclusión (evitar reservas y periodos superpuestos).
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ============================================================================
-- 1. Catálogos y configuración
-- ============================================================================
-- Roles: USUARIO es el supertipo; HUESPED, ANFITRION y ADMINISTRADOR (disjuntos y totales)
-- se resuelven con una sola tabla y la columna rol (sección 6.4 del documento del MER).
CREATE TABLE usuario (
    id_usuario      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(120) NOT NULL,
    correo          VARCHAR(254) NOT NULL,
    contrasena_hash VARCHAR(255) NOT NULL,
    rol             VARCHAR(15)  NOT NULL,
    cuenta_activa   BOOLEAN      NOT NULL DEFAULT TRUE,
    restringido     BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('HUESPED', 'ANFITRION', 'ADMINISTRADOR'))
);
-- Clave natural: el correo es único sin importar mayúsculas.
CREATE UNIQUE INDEX uq_usuario_correo ON usuario (lower(correo));

CREATE TABLE ciudad (
    id_ciudad BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre    VARCHAR(100) NOT NULL,
    CONSTRAINT pk_ciudad PRIMARY KEY (id_ciudad),
    CONSTRAINT uq_ciudad_nombre UNIQUE (nombre)
);

CREATE TABLE tipo_alojamiento (
    id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre  VARCHAR(80) NOT NULL,
    CONSTRAINT pk_tipo_alojamiento PRIMARY KEY (id_tipo),
    CONSTRAINT uq_tipo_alojamiento_nombre UNIQUE (nombre)
);

CREATE TABLE politica_cancelacion (
    id_politica           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre                VARCHAR(80)  NOT NULL,
    horas_anticipacion_min INTEGER      NOT NULL,
    porcentaje_devolucion NUMERIC(5,2) NOT NULL,
    CONSTRAINT pk_politica_cancelacion PRIMARY KEY (id_politica),
    CONSTRAINT uq_politica_cancelacion_nombre UNIQUE (nombre),
    CONSTRAINT ck_politica_horas CHECK (horas_anticipacion_min >= 0),
    CONSTRAINT ck_politica_porcentaje CHECK (porcentaje_devolucion BETWEEN 0 AND 100)
);

-- Servicio (amenity): Wi-Fi, parqueadero, cocina, etc.
CREATE TABLE servicio (
    id_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(80) NOT NULL,
    CONSTRAINT pk_servicio PRIMARY KEY (id_servicio),
    CONSTRAINT uq_servicio_nombre UNIQUE (nombre)
);

-- Una sola fila: porcentajes configurables sin tocar código.
CREATE TABLE configuracion_plataforma (
    id_configuracion          SMALLINT     NOT NULL DEFAULT 1,
    porcentaje_tarifa_servicio NUMERIC(5,2) NOT NULL,
    porcentaje_descuento      NUMERIC(5,2) NOT NULL,
    noches_minimas_descuento  INTEGER      NOT NULL,
    CONSTRAINT pk_configuracion_plataforma PRIMARY KEY (id_configuracion),
    CONSTRAINT ck_configuracion_unica CHECK (id_configuracion = 1),
    CONSTRAINT ck_configuracion_tarifa CHECK (porcentaje_tarifa_servicio BETWEEN 0 AND 100),
    CONSTRAINT ck_configuracion_descuento CHECK (porcentaje_descuento BETWEEN 0 AND 100),
    CONSTRAINT ck_configuracion_noches CHECK (noches_minimas_descuento >= 1)
);

-- ============================================================================
-- 2. Publicaciones
-- ============================================================================
CREATE TABLE publicacion (
    id_publicacion    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_anfitrion      BIGINT        NOT NULL,                  -- REL-01 publica
    id_ciudad         BIGINT        NOT NULL,                  -- REL-02
    id_tipo           BIGINT        NOT NULL,                  -- REL-03
    id_politica       BIGINT        NOT NULL,                  -- REL-04
    titulo            VARCHAR(150)  NOT NULL,
    descripcion       TEXT,
    direccion_textual VARCHAR(250),
    barrio_zona       VARCHAR(120),
    capacidad         INTEGER       NOT NULL,
    precio_noche      NUMERIC(12,2) NOT NULL,
    tarifa_limpieza   NUMERIC(12,2) NOT NULL DEFAULT 0,
    reglas            TEXT,
    estado            VARCHAR(20)   NOT NULL DEFAULT 'BORRADOR',
    CONSTRAINT pk_publicacion PRIMARY KEY (id_publicacion),
    CONSTRAINT fk_publicacion_anfitrion FOREIGN KEY (id_anfitrion) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_publicacion_ciudad    FOREIGN KEY (id_ciudad)    REFERENCES ciudad (id_ciudad),
    CONSTRAINT fk_publicacion_tipo      FOREIGN KEY (id_tipo)      REFERENCES tipo_alojamiento (id_tipo),
    CONSTRAINT fk_publicacion_politica  FOREIGN KEY (id_politica)  REFERENCES politica_cancelacion (id_politica),
    CONSTRAINT ck_publicacion_estado CHECK (estado IN ('BORRADOR', 'PENDIENTE_REVISION', 'ACTIVA', 'PAUSADA', 'BLOQUEADA')),
    CONSTRAINT ck_publicacion_capacidad CHECK (capacidad > 0),
    CONSTRAINT ck_publicacion_precio CHECK (precio_noche > 0),
    CONSTRAINT ck_publicacion_limpieza CHECK (tarifa_limpieza >= 0),
    -- Información mínima de la propia fila para publicar. Las imágenes y los servicios
    -- se validan en la capa de servicio (RF-ALOJ-003).
    CONSTRAINT ck_publicacion_completa CHECK (
        estado NOT IN ('PENDIENTE_REVISION', 'ACTIVA')
        OR (descripcion IS NOT NULL AND direccion_textual IS NOT NULL AND reglas IS NOT NULL)
    )
);

-- Entidad débil de PUBLICACION (REL-19 tiene). Identificador: (id_publicacion, orden).
CREATE TABLE imagen_publicacion (
    id_publicacion BIGINT       NOT NULL,
    orden          INTEGER      NOT NULL,
    ruta           VARCHAR(500) NOT NULL,
    CONSTRAINT pk_imagen_publicacion PRIMARY KEY (id_publicacion, orden),
    CONSTRAINT fk_imagen_publicacion FOREIGN KEY (id_publicacion) REFERENCES publicacion (id_publicacion) ON DELETE CASCADE,
    CONSTRAINT ck_imagen_orden CHECK (orden > 0)
);

-- REL-05 incluye (N:M entre PUBLICACION y SERVICIO).
CREATE TABLE publicacion_servicio (
    id_publicacion BIGINT NOT NULL,
    id_servicio    BIGINT NOT NULL,
    CONSTRAINT pk_publicacion_servicio PRIMARY KEY (id_publicacion, id_servicio),
    CONSTRAINT fk_pubserv_publicacion FOREIGN KEY (id_publicacion) REFERENCES publicacion (id_publicacion) ON DELETE CASCADE,
    CONSTRAINT fk_pubserv_servicio    FOREIGN KEY (id_servicio)    REFERENCES servicio (id_servicio)
);

-- Entidad débil de PUBLICACION (REL-06 ofrece). Identificador: (id_publicacion, nombre).
CREATE TABLE servicio_adicional (
    id_publicacion BIGINT        NOT NULL,
    nombre         VARCHAR(100)  NOT NULL,
    precio         NUMERIC(12,2) NOT NULL,
    tipo_cobro     VARCHAR(20)   NOT NULL,
    CONSTRAINT pk_servicio_adicional PRIMARY KEY (id_publicacion, nombre),
    CONSTRAINT fk_servicio_adicional_publicacion FOREIGN KEY (id_publicacion) REFERENCES publicacion (id_publicacion) ON DELETE CASCADE,
    CONSTRAINT ck_servicio_adicional_precio CHECK (precio >= 0)
);

-- ============================================================================
-- 3. Reservas y disponibilidad
-- ============================================================================
CREATE TABLE reserva (
    id_reserva                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_huesped                    BIGINT        NOT NULL,      -- REL-08 realiza
    id_publicacion                BIGINT        NOT NULL,      -- REL-09 recibe
    fecha_llegada                 DATE          NOT NULL,
    fecha_salida                  DATE          NOT NULL,
    estado                        VARCHAR(20)   NOT NULL DEFAULT 'CONFIRMADA',
    clave_idempotencia            VARCHAR(100)  NOT NULL,
    precio_base                   NUMERIC(12,2) NOT NULL,
    porcentaje_descuento_aplicado NUMERIC(5,2)  NOT NULL DEFAULT 0,
    valor_descuento               NUMERIC(12,2) NOT NULL DEFAULT 0,
    tarifa_limpieza               NUMERIC(12,2) NOT NULL DEFAULT 0,
    porcentaje_tarifa_servicio    NUMERIC(5,2)  NOT NULL,
    tarifa_servicio               NUMERIC(12,2) NOT NULL,
    total                         NUMERIC(12,2) NOT NULL,
    horas_anticipacion_aplicada   INTEGER       NOT NULL,
    porcentaje_devolucion_aplicado NUMERIC(5,2) NOT NULL,
    CONSTRAINT pk_reserva PRIMARY KEY (id_reserva),
    CONSTRAINT fk_reserva_huesped     FOREIGN KEY (id_huesped)     REFERENCES usuario (id_usuario),
    CONSTRAINT fk_reserva_publicacion FOREIGN KEY (id_publicacion) REFERENCES publicacion (id_publicacion),
    -- Una clave por huésped: protege contra reservas duplicadas ante reintentos (RNF-CONF-001).
    CONSTRAINT uq_reserva_idempotencia UNIQUE (id_huesped, clave_idempotencia),
    -- Permite que tablas hijas verifiquen que pertenecen a la misma publicación de la reserva.
    CONSTRAINT uq_reserva_publicacion UNIQUE (id_reserva, id_publicacion),
    CONSTRAINT ck_reserva_estado CHECK (estado IN ('CONFIRMADA', 'CANCELADA', 'REVISION_MANUAL')),
    CONSTRAINT ck_reserva_fechas CHECK (fecha_salida > fecha_llegada),
    CONSTRAINT ck_reserva_montos CHECK (
        precio_base >= 0 AND valor_descuento >= 0 AND valor_descuento <= precio_base
        AND tarifa_limpieza >= 0 AND tarifa_servicio >= 0 AND total >= 0
    ),
    CONSTRAINT ck_reserva_porcentajes CHECK (
        porcentaje_descuento_aplicado BETWEEN 0 AND 100
        AND porcentaje_tarifa_servicio BETWEEN 0 AND 100
        AND porcentaje_devolucion_aplicado BETWEEN 0 AND 100
    ),
    CONSTRAINT ck_reserva_horas CHECK (horas_anticipacion_aplicada >= 0),
    -- Evita la doble reserva por concurrencia (RF-RES-002): la fecha de salida no cuenta como noche ocupada.
    -- CANCELADA no ocupa fechas; REVISION_MANUAL sí, porque la reserva futura se conserva tras un bloqueo.
    CONSTRAINT ex_reserva_sin_solape EXCLUDE USING gist (
        id_publicacion WITH =,
        daterange(fecha_llegada, fecha_salida, '[)') WITH &&
    ) WHERE (estado IN ('CONFIRMADA', 'REVISION_MANUAL'))
);

-- REL-10 incluye_adicional (N:M entre RESERVA y SERVICIO_ADICIONAL, con costo_aplicado).
-- La primera llave foránea obliga a que el servicio sea de la misma publicación de la reserva.
CREATE TABLE reserva_servicio_adicional (
    id_reserva     BIGINT        NOT NULL,
    id_publicacion BIGINT        NOT NULL,
    nombre         VARCHAR(100)  NOT NULL,
    costo_aplicado NUMERIC(12,2) NOT NULL,
    CONSTRAINT pk_reserva_servicio_adicional PRIMARY KEY (id_reserva, id_publicacion, nombre),
    CONSTRAINT fk_rsa_reserva FOREIGN KEY (id_reserva, id_publicacion)
        REFERENCES reserva (id_reserva, id_publicacion) ON DELETE CASCADE,
    CONSTRAINT fk_rsa_servicio_adicional FOREIGN KEY (id_publicacion, nombre)
        REFERENCES servicio_adicional (id_publicacion, nombre),
    CONSTRAINT ck_rsa_costo CHECK (costo_aplicado >= 0)
);

-- REL-07 define. fecha_fin NO se incluye en el periodo (mismo criterio que fecha_salida en reserva).
CREATE TABLE periodo_disponibilidad (
    id_periodo     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_publicacion BIGINT      NOT NULL,
    id_reserva     BIGINT,                                     -- REL-18 bloquea (solo si tipo = RESERVADO)
    fecha_inicio   DATE        NOT NULL,
    fecha_fin      DATE        NOT NULL,
    tipo           VARCHAR(10) NOT NULL,
    CONSTRAINT pk_periodo_disponibilidad PRIMARY KEY (id_periodo),
    CONSTRAINT fk_periodo_publicacion FOREIGN KEY (id_publicacion) REFERENCES publicacion (id_publicacion) ON DELETE CASCADE,
    -- Con id_reserva nulo la llave no se evalúa; con valor, garantiza misma publicación que la reserva.
    CONSTRAINT fk_periodo_reserva FOREIGN KEY (id_reserva, id_publicacion)
        REFERENCES reserva (id_reserva, id_publicacion),
    CONSTRAINT uq_periodo_reserva UNIQUE (id_reserva),
    CONSTRAINT ck_periodo_tipo CHECK (tipo IN ('DISPONIBLE', 'RESERVADO', 'BLOQUEADO')),
    CONSTRAINT ck_periodo_fechas CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT ck_periodo_reserva CHECK ((tipo = 'RESERVADO') = (id_reserva IS NOT NULL)),
    -- Los periodos de una publicación no se superponen. Es DEFERRABLE para poder dividir un
    -- periodo disponible al reservar (SET CONSTRAINTS ex_periodo_sin_solape DEFERRED).
    CONSTRAINT ex_periodo_sin_solape EXCLUDE USING gist (
        id_publicacion WITH =,
        daterange(fecha_inicio, fecha_fin, '[)') WITH &&
    ) DEFERRABLE INITIALLY IMMEDIATE
);

